import { db } from "./firebase-config.js";
import { collection, getDocs, query, where } from "https://www.gstatic.com/firebasejs/10.12.5/firebase-firestore.js";

const user = HMS.protect("patient");

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function predictionView(prediction) {
  return `
    <section class="gradient-panel" style="margin-bottom:32px">
      <div class="row start"><span class="icon-box" style="background:rgba(255,255,255,.2);color:#fff">${HMS.icon("activity")}</span><div><h2>AI Health Assessment</h2><p class="muted">Generated by your healthcare staff</p></div></div>
      <div class="grid grid-2">
        <div><p class="muted">Overall Risk Level</p><span class="badge ${prediction.riskLevel === "high" ? "red" : prediction.riskLevel === "medium" ? "amber" : "green"}" style="font-size:18px">${escapeHtml(String(prediction.riskLevel || "-").toUpperCase())}</span></div>
        <div><p class="muted">Prediction Confidence</p><div class="row"><div class="progress" style="flex:1"><span style="width:${Number(prediction.confidence || 0)}%"></span></div><strong>${escapeHtml(prediction.confidence || "-")}${prediction.confidence ? "%" : ""}</strong></div></div>
      </div>
    </section>
    <section class="card pad" style="margin-bottom:32px">
      <h3 class="section-title">${HMS.icon("chart")} Prediction Summary</h3>
      <div class="grid grid-2">
        <div class="soft-panel"><p class="label">Risk Score</p><p class="profile-display-value">${escapeHtml(prediction.riskScore || "-")}</p></div>
        <div class="soft-panel"><p class="label">Created At</p><p class="profile-display-value">${escapeHtml(prediction.createdAtLabel || "-")}</p></div>
      </div>
    </section>
    <section class="card pad">
      <h3>Prediction Explanation</h3>
      <div class="soft-panel"><p>${escapeHtml(prediction.explanation || "-")}</p></div>
      <div class="amber-panel prediction-note" style="padding:16px;border-radius:8px;margin-top:24px">
        <p><strong>Note:</strong> These predictions are AI-generated and should be reviewed by a healthcare professional.</p>
      </div>
    </section>
  `;
}

function emptyPredictionState() {
  return `
    <section class="card">
      <div class="empty-state">
        <span class="icon-box">${HMS.icon("activity")}</span>
        <h3>No Health Prediction Yet</h3>
        <p class="muted empty-state-copy">Your health prediction will appear here after a healthcare staff member runs an AI prediction for your case.</p>
      </div>
    </section>
  `;
}

if (user) {
  let predictionMarkup = emptyPredictionState();

  try {
    const predictionQuery = query(
      collection(db, "predictions"),
      where("userId", "==", user.id)
    );
    const snapshot = await getDocs(predictionQuery);

    if (!snapshot.empty) {
      const predictions = snapshot.docs
        .map((documentSnapshot) => documentSnapshot.data())
        .sort((a, b) => {
          const aTime = a.updatedAt?.toMillis?.() || a.createdAt?.toMillis?.() || 0;
          const bTime = b.updatedAt?.toMillis?.() || b.createdAt?.toMillis?.() || 0;
          return bTime - aTime;
        });
      const latestPrediction = predictions[0];
      const createdAtLabel = latestPrediction.updatedAt?.toDate
        ? latestPrediction.updatedAt.toDate().toLocaleString("en-SG")
        : latestPrediction.createdAt?.toDate
          ? latestPrediction.createdAt.toDate().toLocaleString("en-SG")
          : "";
      predictionMarkup = predictionView({
        ...latestPrediction,
        createdAtLabel
      });
    }
  } catch {
    predictionMarkup = emptyPredictionState();
  }

  HMS.renderShell("patient-health-prediction.html", `
    <section class="page">
      <div class="page-header">
        <div>
          <h1 class="page-title">Health Prediction</h1>
          <p class="page-subtitle">AI prediction results generated by your healthcare staff will appear here once available.</p>
        </div>
      </div>
      ${predictionMarkup}
    </section>
  `);
}
