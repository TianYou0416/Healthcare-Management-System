import { db } from "./firebase-config.js";
import { collection, getDocs, query, where } from "https://www.gstatic.com/firebasejs/10.12.5/firebase-firestore.js";

const user = HMS.protect("patient");

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function displayValue(value) {
  const safeValue = String(value ?? "").trim();
  return safeValue || "-";
}

function riskBadgeClass(level) {
  return HMS.riskClass(String(level || "").toLowerCase());
}

function formatTimestamp(prediction) {
  const timestamp = prediction.updatedAt || prediction.createdAt;
  if (timestamp?.toDate) return timestamp.toDate().toLocaleString("en-SG");
  return "";
}

function predictionTime(prediction) {
  return prediction.updatedAt?.toMillis?.() || prediction.createdAt?.toMillis?.() || 0;
}

async function fetchPatientPredictions() {
  const queriesToTry = [
    query(collection(db, "predictions"), where("userId", "==", user.id)),
    query(collection(db, "predictions"), where("patientUserId", "==", user.id)),
    user.email ? query(collection(db, "predictions"), where("patientEmail", "==", user.email)) : null
  ].filter(Boolean);

  const predictionMap = new Map();
  const errors = [];

  for (const lookupQuery of queriesToTry) {
    try {
      const snapshot = await getDocs(lookupQuery);
      snapshot.forEach((documentSnapshot) => {
        predictionMap.set(documentSnapshot.id, {
          id: documentSnapshot.id,
          ...documentSnapshot.data()
        });
      });
    } catch (error) {
      errors.push(error);
    }
  }

  if (!predictionMap.size && errors.length === queriesToTry.length) {
    throw errors[0];
  }

  return Array.from(predictionMap.values())
    .sort((a, b) => predictionTime(b) - predictionTime(a));
}

function topFactorCard(factor) {
  const impact = Number(factor.impact_percentage || 0);

  return `
    <article class="card pad patient-factor-card">
      <div class="row between start">
        <div>
          <strong>${escapeHtml(displayValue(factor.label))}</strong>
          <p class="small muted">${escapeHtml(displayValue(factor.value))}</p>
        </div>
        <span class="badge blue">${escapeHtml(impact.toFixed(2))}%</span>
      </div>
      <div class="row">
        <div class="progress gray" style="flex:1"><span style="width:${Math.min(impact, 100)}%"></span></div>
        <strong class="small">${escapeHtml(displayValue(factor.feature))}</strong>
      </div>
    </article>
  `;
}

function recommendationItem(text) {
  return `
    <div class="blue-panel row start patient-recommendation-row">
      ${HMS.icon("check")}
      <p>${escapeHtml(text)}</p>
    </div>
  `;
}

function predictionHistoryItem(prediction) {
  return `
    <tr>
      <td>${escapeHtml(formatTimestamp(prediction) || "-")}</td>
      <td><span class="badge ${prediction.prolongedLos === "Yes" ? "red" : "green"}">${escapeHtml(displayValue(prediction.prolongedLos))}</span></td>
      <td><span class="badge ${riskBadgeClass(prediction.riskLevel)}">${escapeHtml(displayValue(prediction.riskLevel))}</span></td>
      <td>${escapeHtml(Math.round(Number(prediction.probability || 0) * 100))}%</td>
      <td>${escapeHtml(displayValue(prediction.model))}</td>
    </tr>
  `;
}

function predictionView(predictions) {
  const latest = predictions[0];
  const probability = Number(latest.probability || 0);
  const topFactors = Array.isArray(latest.topFactors) ? latest.topFactors : [];
  const recommendations = Array.isArray(latest.clinicalRecommendations) ? latest.clinicalRecommendations : [];

  return `
    <section class="gradient-panel patient-prediction-hero">
      <div class="row start">
        <span class="icon-box" style="background:rgba(255,255,255,.2);color:#fff">${HMS.icon("activity")}</span>
        <div>
          <h2>AI Health Prediction Result</h2>
          <p class="muted">Generated by your healthcare staff${formatTimestamp(latest) ? ` on ${escapeHtml(formatTimestamp(latest))}` : ""}</p>
        </div>
      </div>
      <div class="grid grid-3">
        <div>
          <p class="muted">Prolonged LOS</p>
          <span class="badge ${latest.prolongedLos === "Yes" ? "red" : "green"}" style="font-size:18px">${escapeHtml(displayValue(latest.prolongedLos))}</span>
        </div>
        <div>
          <p class="muted">Risk Level</p>
          <span class="badge ${riskBadgeClass(latest.riskLevel)}" style="font-size:18px">${escapeHtml(displayValue(latest.riskLevel))}</span>
        </div>
        <div>
          <p class="muted">Probability</p>
          <div class="row">
            <div class="progress" style="flex:1"><span style="width:${Math.round(probability * 100)}%"></span></div>
            <strong>${Math.round(probability * 100)}%</strong>
          </div>
        </div>
      </div>
    </section>

    <section class="card pad patient-prediction-section">
      <h3 class="section-title">${HMS.icon("chart")} Prediction Summary</h3>
      <div class="grid grid-4">
        <div class="soft-panel"><p class="label">Model</p><p class="profile-display-value">${escapeHtml(displayValue(latest.model))}</p></div>
        <div class="soft-panel"><p class="label">Dataset</p><p class="profile-display-value">${escapeHtml(displayValue(latest.dataset))}</p></div>
        <div class="soft-panel"><p class="label">Threshold</p><p class="profile-display-value">${escapeHtml(displayValue(latest.threshold))}</p></div>
        <div class="soft-panel"><p class="label">Status</p><p class="profile-display-value">${escapeHtml(displayValue(latest.status))}</p></div>
      </div>
    </section>

    <section class="card pad patient-prediction-section">
      <h3 class="section-title">${HMS.icon("brain")} Key Factors Behind This Prediction</h3>
      <p class="muted">These factors show which clinical details had the strongest influence on the AI result.</p>
      ${topFactors.length ? `<div class="grid grid-2 patient-factor-grid">${topFactors.map(topFactorCard).join("")}</div>` : `<p class="muted" style="margin-top:16px">No explanation factors available.</p>`}
    </section>

    <section class="card pad patient-prediction-section">
      <h3>Clinical Recommendations</h3>
      ${recommendations.length ? recommendations.map(recommendationItem).join("") : `<p class="muted">No recommendations available.</p>`}
      <div class="amber-panel prediction-note">
        <p><strong>Note:</strong> These predictions are AI-generated and should be reviewed by your healthcare professional.</p>
      </div>
    </section>

    <section class="card table-wrap patient-prediction-section">
      <div class="patient-history-note">
        <p class="small muted">Prediction history is shown for reference only. To view the complete AI report, open <a class="link" href="patient-medical-records.html">Medical Records</a>.</p>
      </div>
      <table>
        <thead><tr><th>Date</th><th>Prolonged LOS</th><th>Risk Level</th><th>Probability</th><th>Model</th></tr></thead>
        <tbody>${predictions.map(predictionHistoryItem).join("")}</tbody>
      </table>
    </section>
  `;
}

function emptyPredictionState() {
  return `
    <section class="card">
      <div class="empty-state">
        <span class="icon-box">${HMS.icon("activity")}</span>
        <h3>No Health Prediction Yet</h3>
        <p class="muted empty-state-copy">Your health prediction will appear here after a healthcare staff member runs an AI prediction for your case.</p>
      </div>
    </section>
  `;
}

if (user) {
  let predictionMarkup = emptyPredictionState();
  let loadError = "";

  try {
    const predictions = await fetchPatientPredictions();
    if (predictions.length) predictionMarkup = predictionView(predictions);
  } catch (error) {
    loadError = error.message || "Unable to load health predictions right now.";
  }

  HMS.renderShell("patient-health-prediction.html", `
    <section class="page">
      <div class="page-header">
        <div>
          <h1 class="page-title">Health Prediction</h1>
          <p class="page-subtitle">AI prediction results generated by your healthcare staff will appear here once available.</p>
        </div>
      </div>
      ${loadError ? `<p class="profile-status error" style="margin-bottom:16px">${escapeHtml(loadError)}</p>` : ""}
      ${predictionMarkup}
    </section>
  `);
}
